#!/usr/bin/env node
/**
 * Generates src/lib/geo-data.ts — simplified, projected SVG paths for Nepal's
 * seven provinces — from the MIT-licensed geoJSON-Nepal dataset by Saugat Acharya
 * (https://github.com/mesaugat/geoJSON-Nepal).
 *
 * Usage: node scripts/generate-map.mjs [path/to/nepal-states.geojson]
 * Without a path the file is downloaded from GitHub.
 */
import { readFile, writeFile } from "node:fs/promises";
import { geoMercator, geoPath, geoCentroid } from "d3-geo";

const SRC = "https://raw.githubusercontent.com/mesaugat/geoJSON-Nepal/master/nepal-states.geojson";
const W = 1000;
const H = 560;
const PAD = 18;
const TOLERANCE = 0.9; // px in projected space

const NAMES = {
  NP01: { slug: "koshi", name: "Koshi", ne: "कोशी" },
  NP02: { slug: "madhesh", name: "Madhesh", ne: "मधेश" },
  NP03: { slug: "bagmati", name: "Bagmati", ne: "बागमती" },
  NP04: { slug: "gandaki", name: "Gandaki", ne: "गण्डकी" },
  NP05: { slug: "lumbini", name: "Lumbini", ne: "लुम्बिनी" },
  NP06: { slug: "karnali", name: "Karnali", ne: "कर्णाली" },
  NP07: { slug: "sudurpashchim", name: "Sudurpashchim", ne: "सुदूरपश्चिम" },
};

function dp(points, tol) {
  if (points.length < 3) return points;
  const sq = tol * tol;
  const keep = new Uint8Array(points.length);
  keep[0] = keep[points.length - 1] = 1;
  const stack = [[0, points.length - 1]];
  while (stack.length) {
    const [a, b] = stack.pop();
    const [ax, ay] = points[a];
    const [bx, by] = points[b];
    const dx = bx - ax;
    const dy = by - ay;
    const len = dx * dx + dy * dy || 1;
    let maxD = -1;
    let idx = -1;
    for (let i = a + 1; i < b; i++) {
      const [px, py] = points[i];
      const t = Math.max(0, Math.min(1, ((px - ax) * dx + (py - ay) * dy) / len));
      const ex = ax + t * dx - px;
      const ey = ay + t * dy - py;
      const d = ex * ex + ey * ey;
      if (d > maxD) {
        maxD = d;
        idx = i;
      }
    }
    if (maxD > sq && idx > 0) {
      keep[idx] = 1;
      stack.push([a, idx], [idx, b]);
    }
  }
  return points.filter((_, i) => keep[i]);
}

const r1 = (n) => Math.round(n * 10) / 10;

async function main() {
  const local = process.argv[2];
  const raw = local ? await readFile(local, "utf8") : await (await fetch(SRC)).text();
  const geo = JSON.parse(raw);
  const projection = geoMercator().fitExtent(
    [
      [PAD, PAD],
      [W - PAD, H - PAD],
    ],
    geo,
  );
  const path = geoPath(projection);
  const provinces = geo.features.map((f) => {
    const meta = NAMES[f.properties.ADM1_PCODE];
    const polys = f.geometry.type === "MultiPolygon" ? f.geometry.coordinates : [f.geometry.coordinates];
    let d = "";
    for (const poly of polys) {
      for (const ring of poly) {
        const projected = ring.map((c) => projection(c));
        const simple = dp(projected, TOLERANCE);
        if (simple.length < 4) continue;
        d += "M" + simple.map(([x, y]) => `${r1(x)} ${r1(y)}`).join("L") + "Z";
      }
    }
    const [cx, cy] = path.centroid(f);
    const [clon, clat] = geoCentroid(f);
    return { ...meta, d, label: [r1(cx), r1(cy)], centroid: [r1(clon * 100) / 100, r1(clat * 100) / 100] };
  });
  const [tx, ty] = projection.translate();
  const k = projection.scale();
  const out = `/* Generated by scripts/generate-map.mjs — do not edit by hand.
 * Province boundaries: geoJSON-Nepal by Saugat Acharya, MIT licence
 * (https://github.com/mesaugat/geoJSON-Nepal), projected (Mercator) and simplified.
 */
export const MAP_W = ${W};
export const MAP_H = ${H};
export const projection = { k: ${k}, tx: ${tx}, ty: ${ty} };

export interface Province {
  slug: string;
  name: string;
  ne: string;
  d: string;
  label: [number, number];
  centroid: [number, number];
}

export const provinces: Province[] = ${JSON.stringify(provinces, null, 0)};

/** Project longitude/latitude (degrees) to map coordinates (Mercator, as generated). */
export function project(lon: number, lat: number): [number, number] {
  const l = (lon * Math.PI) / 180;
  const p = (lat * Math.PI) / 180;
  return [projection.tx + projection.k * l, projection.ty - projection.k * Math.log(Math.tan(Math.PI / 4 + p / 2))];
}
`;
  await writeFile(new URL("../src/lib/geo-data.ts", import.meta.url), out);
  console.log("wrote src/lib/geo-data.ts", provinces.map((p) => `${p.slug}:${p.d.length}`).join(" "));
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
